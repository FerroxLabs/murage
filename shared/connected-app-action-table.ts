// What a completed connected-app action proves, by its exact slug.
//
// The reply check (server/reply-action-guard.ts) marks a closing reply that says
// "Sent." or "I've added both events to your calendar." with no matching record.
// A connected-app action is a record only for the classes listed here, and only
// for the classes a plain reply about it would truthfully claim:
//   - a send, post, reply, forward or message that is delivered is `send`
//     (Discord's CREATE_MESSAGE posts to the channel, so it is `send`);
//   - a draft is `save`, never `send`; only SEND_DRAFT sends one;
//   - a real calendar event made, imported or quick-added is `save` + `schedule`,
//     and an event edited is `change` + `save` + `schedule`; only a calendar
//     app's own entry here proves an event, never a name ending in CREATE_EVENT;
//   - deleting or cancelling the main object (an email, event, file, message,
//     task, page...) is `delete`;
//   - settings, rules, filters, labels, ACLs and permissions, attachments,
//     extensions, sharing and access carry nothing, so they are not listed.
// A slug that is not listed proves nothing, except the three exact suffixes in
// `FALLBACK`, which mean the same thing in every app.
//
// Every slug was checked against the provider catalogue at
// https://docs.composio.dev/toolkits/<toolkit> on 2026-10-15. A slug that could
// not be found there or in the repo's own fixtures is left out: unknown means
// unproven, never proven.
