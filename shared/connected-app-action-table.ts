/** Every listed slug, in full ("GOOGLECALENDAR_CREATE_EVENT"). */
export const CONNECTED_APP_ACTIONS: ReadonlyMap<string, Classes> = new Map(
  Object.entries(CONNECTED_APP_ACTION_TABLE).flatMap(([toolkit, actions]) =>
    Object.entries(actions).map(([action, classes]) => [`${toolkit}_${action}`, classes] as const)),
);

/** A slug no table entry names proves something only by one of these exact endings. */
const FALLBACK: Array<[RegExp, Classes]> = [
  [/_SEND_EMAIL$/, SEND],
  [/_SEND_MESSAGE$/, SEND],
  [/_CREATE_DRAFT$/, SAVE],
];

/** The classes a completed connected-app action carries, from its exact slug in
 * any case or spelling ("GOOGLECALENDAR_CREATE_EVENT", "googlecalendar create event"). */
export function connectedAppActionClasses(slug: string): ActionClass[] {
  const key = slug.trim().toUpperCase().replace(/[^A-Z0-9]+/g, "_").replace(/^_+|_+$/g, "");
  const listed = CONNECTED_APP_ACTIONS.get(key) ?? FALLBACK.find(([ending]) => ending.test(key))?.[1];
  return listed ? [...listed] : [];
}
