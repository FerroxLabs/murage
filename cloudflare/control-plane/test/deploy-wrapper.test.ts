/** The injected D1 runner (KMS 10.4, 12.3): an in-memory image_policy row, every statement logged in `events` with the wrangler run, so tests see the ORDER. */
function epochIo(o: { start?: number; bundle?: number | null; d1?: "throw" | "stale" | "missing" | "none"; events?: string[]; links?: unknown; marker?: unknown;
  markThrows?: boolean } = {}) {
  const events = o.events ?? []; const state = { epoch: o.start ?? 0, marker: "marker" in o ? o.marker : 0 as unknown };
  const source = o.bundle === null ? "// no epoch here" : `export const IMAGE_POLICY_EPOCH = ${o.bundle ?? 7};`;
  const d1 = async (sql: string) => {
    // FLUX-ENSURE-EMAIL-VERIFIED: the production flux_links count (deploy.mjs fluxLinksPreflight), its own event so the ORDER is visible.
    // M4: the one-time rollout marker, written only after a first production deploy succeeded.
    if (/^INSERT OR IGNORE INTO flux_email_proof_rollout/.test(sql)) { events.push("d1:mark"); if (o.markThrows) throw new Error("d1 down"); state.marker = 1; return { results: [] }; }
    if (/FROM flux_links/.test(sql)) {
      events.push("d1:links"); if (o.d1 === "throw" && o.links !== 0) throw new Error("d1 down");
      return { results: o.links === "no-row" ? [] : [{ marker: state.marker, n: "links" in o ? o.links : 0 }] };
    }
    events.push(`d1:${sql.split(" ")[0]}`);
    if (o.d1 === "throw") throw new Error("d1 down");
    const m = /VALUES \('current',(\d+)\)/.exec(sql);
    if (m && o.d1 !== "stale") state.epoch = Math.max(state.epoch, Number(m[1]));
    if (/^SELECT/.test(sql)) return { results: o.d1 === "missing" ? [] : [{ epoch: state.epoch }] };
    return { results: [] };
  };
  return { events, state, bundle: o.bundle ?? 7, io: { ...(o.d1 === "none" ? {} : { d1 }), bundleEpoch: source } };
}
