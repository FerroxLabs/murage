  const LISTED = { success: true, errors: [], messages: [], result: [] };
  type Answer = { status: number; body?: unknown } | Error;
  /** A fake Cloudflare: the token works in `own` and is denied in the other account, unless an answer says otherwise. */
  function cloudflare(own: string, answers: { own?: Answer; other?: Answer } = {}) {
    const calls: { url: string; init?: RequestInit }[] = [];
    const impl = async (url: string, init?: RequestInit) => {
      calls.push({ url, init });
      const isOwn = url.includes(`/accounts/${own}/`);
      const answer = (isOwn ? answers.own : answers.other) ?? (isOwn ? { status: 200, body: LISTED } : { status: 403, body: DENIED });
      if (answer instanceof Error) throw answer;
      return new Response(answer.body === undefined ? "not json" : JSON.stringify(answer.body), { status: answer.status });
    };
    return { impl, calls };
  }
