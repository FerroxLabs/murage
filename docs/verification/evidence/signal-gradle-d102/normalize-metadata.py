import collections, hashlib, json, pathlib, re, subprocess, xml.etree.ElementTree as E
job=pathlib.Path('/job'); out=pathlib.Path('/evidence'); cache=job/'gradle/caches/modules-2/files-2.1'
ns='https://schema.gradle.org/dependency-verification'; tag=lambda x:'{'+ns+'}'+x
E.register_namespace('',ns); E.register_namespace('xsi','http://www.w3.org/2001/XMLSchema-instance')
tree=E.parse(job/'source/gradle/verification-metadata.xml'); root=tree.getroot(); config=root.find(tag('configuration'))
for child in list(config):
    if child.tag not in [tag('verify-metadata'),tag('verify-signatures')]: config.remove(child)
E.SubElement(config,tag('key-servers'),{'enabled':'false'})
home=out/'metadata-gnupg'; gpg=['gpg','--homedir',str(home),'--batch','--no-auto-key-retrieve','--status-fd','1']
res=subprocess.run(gpg[:-2]+['--export'],check=True,capture_output=True)
(out/'all-keys.gpg').write_bytes((job/'source/gradle/verification-keyring.gpg').read_bytes()+res.stdout)
rows=[]; keys=set(); fallbacks=set()
for comp in root.find(tag('components')):
    group,name,version=[comp.attrib[x] for x in ['group','name','version']]
    for art in comp:
        filename=art.attrib['name']; files=list((cache/group/name/version).glob('*/'+filename))
        assert len(files)==1,(group,name,version,filename,files)
        file=files[0]; sha=hashlib.sha256(file.read_bytes()).hexdigest()
        assert sha in [e.attrib['value'] for e in art.findall(tag('sha256'))],(filename,'SHA mismatch')
        for child in list(art): art.remove(child)
        signature_files=list((cache/group/name/version).glob('*/'+filename+'.asc'))
        row={'group':group,'name':name,'version':version,'artifact':filename,'sha256':sha}
        if signature_files:
            assert len(signature_files)==1
            res=subprocess.run(gpg+['--verify',str(signature_files[0]),str(file)],capture_output=True,text=True,errors='replace')
            valid=[l.split() for l in res.stdout.splitlines() if l.startswith('[GNUPG:] VALIDSIG ')]
            if valid:
                assert len(valid)==1 and '[GNUPG:] BADSIG ' not in res.stdout
                key=valid[0][2]; assert len(key)==40
                E.SubElement(art,tag('pgp'),{'value':key}); row['pgp']=key; keys.add(key)
            else:
                missing=[l.split()[2] for l in res.stdout.splitlines() if l.startswith('[GNUPG:] NO_PUBKEY ')]
                assert missing,(filename,res.stdout,res.stderr)
                if group=='org.signal' and name=='libsignal-client' and set(missing)=={'BB7EE61AD5989884'}:
                    # Gradle's original generation verified this key. Its stripped
                    # packet has no UID, so GnuPG cannot import it; Gradle can.
                    key='2F6EB0E577CA8474A2F9E676BB7EE61AD5989884'
                    E.SubElement(art,tag('pgp'),{'value':key}); row['pgp']=key; row['signatureVerifier']='Gradle'; keys.add(key)
                else:
                    ignored=E.SubElement(art,tag('ignored-keys'))
                    for key in sorted(set(missing)):
                        E.SubElement(ignored,tag('ignored-key'),{'id':key,'reason':'Signer public key unavailable or not importable from Ubuntu and OpenPGP keyservers during generation; exact SHA256 required'})
                        fallbacks.add(key)
                    row['missingKeys']=sorted(set(missing))
        else: row['signature']='not published/retrievable during Gradle generation; exact SHA256 required'
        E.SubElement(art,tag('sha256'),{'value':sha,'origin':'Generated by Gradle; checked against resolved artifact'})
        rows.append(row)
E.indent(tree,space='   '); dest=out/'metadata'; dest.mkdir(exist_ok=True)
tree.write(dest/'verification-metadata.xml',encoding='UTF-8',xml_declaration=True)
# Export only keys actually used, in stable fingerprint order.
res=subprocess.run(gpg[:-2]+['--armor','--export',*sorted(keys)],check=True,capture_output=True)
original=(job/'source/gradle/verification-keyring.keys').read_text()
signal=re.search(r'pub    BB7EE61AD5989884\n(-----BEGIN PGP PUBLIC KEY BLOCK-----.*?-----END PGP PUBLIC KEY BLOCK-----)',original,re.S).group(1)
(dest/'verification-keyring.keys').write_bytes(res.stdout+b'\n'+signal.encode()+b'\n')
summary={'components':len(root.find(tag('components'))),'artifacts':len(rows),'sha256':len(rows),'pgpArtifacts':sum('pgp' in r for r in rows),'pgpSigningKeys':len(keys),'sha256Only':sum('pgp' not in r for r in rows),'missingKeys':sorted(fallbacks),'extensions':dict(sorted(collections.Counter(pathlib.Path(r['artifact']).suffix for r in rows).items()))}
(out/'evidence/closure.json').write_text(json.dumps({'summary':summary,'artifacts':rows},indent=2)+'\n')
print(json.dumps(summary,indent=2))
