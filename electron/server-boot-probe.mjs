import { createHash } from "node:crypto";
import { PROOF_CHALLENGE_HEADER, newChallenge, proofHolds } from "../shared/boot-proof.mjs";
// Kernel of the packaged-server boot wait (see issue #506): poll a freshly
// forked child's /api/health until it either proves its identity, we learn
// some other process owns the port, or the wall-clock budget runs out.
//
// Extracted from electron/main.mjs so the failure modes below can carry
// regression tests without booting Electron (main.mjs is not importable in a
// bare node test — importing it starts the whole app bootstrap).
//
// - The budget is wall-clock and shared by every step: each in-flight probe is
//   aborted at the remaining deadline, so a server that accepts connections
//   but never answers cannot wedge the launcher past its own timeout.
// - ANY HTTP answer on the port proves somebody owns it. Only our own child's
//   identity payload counts as ready; everything else (a 404/503 from an
//   unrelated app, wrong pid, non-JSON body) is reported as a foreign owner
//   immediately instead of burning the rest of the budget re-polling a port
//   we will never win.
// - Identity is a per-launch nonce (generated by the shell, passed only to the
//   child in its environment, echoed in the child's health answers). It does not
//   depend on the child's pid, which is public and, for Electron's utilityProcess,
//   only known after the async `spawn` event.

// A refused local connection costs next to nothing, and this interval is the
// worst-case wait between the port opening and the window starting.
// A healthy child usually binds within a few seconds of fork, and a refused
// loopback connect costs well under a millisecond, so poll briskly over that
// window; slower boots fall back to the old interval (OpenMausBot #2390,
// Apache-2.0).
export const BOOT_PROBE_FAST_INTERVAL_MS = 25;
export const BOOT_PROBE_FAST_WINDOW_MS = 5_000;
export const BOOT_PROBE_INTERVAL_MS = 100;
/** A running memory upgrade keeps the wait going in steps of this size ... */
export const BOOT_EXTEND_STEP_MS = 5_000;
/** ... but never past this, so a wedged child is still reaped. */
export const BOOT_EXTEND_LIMIT_MS = 30 * 60_000;
/** Past the limit the upgrade may go on only while its note keeps moving, and never beyond this. */
export const BOOT_EXTEND_ABSOLUTE_MS = 6 * 60 * 60_000;
/** How often an upgrading child is asked again, and how long after its last "upgrading" answer it still counts as upgrading. */
export const BOOT_UPGRADING_POLL_MS = 250;
export const UPGRADING_FRESH_MS = 10_000;
/** A gap this long between two turns of the probe loop is taken to be sleep. */
export const SLEEP_GAP_MS = 30_000;

/** What a child's health answer carries for a nonce the shell gave it: the SHA-256 of the nonce (the nonce itself never leaves the child). */
export const launchOf = (nonce) => createHash("sha256").update(String(nonce)).digest("hex");

const defaultSleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

/**
 * @param {{
 *   port: number,
 *   nonce: () => string | undefined,
 *   bootTimeoutMs: number,
 *   isExited?: () => boolean,
 *   now?: () => number,
 *   sleep?: (ms: number) => Promise<void>,
 *   fetchImpl?: typeof fetch,
 *   extendWhile?: () => boolean,
 * }} options
 * @returns {Promise<{ outcome: "ready" | "foreign-owner" | "timeout" | "exited" }>}
*/
export async function pollServerIdentity({
  port,
  nonce,
  bootTimeoutMs,
  isExited = () => false,
  now = Date.now,
  sleep = defaultSleep,
  fetchImpl = globalThis.fetch,
  extendWhile = () => false,
  // True while the child's note keeps changing: the 30-minute cap is then not the end of a
  // resumable upgrade that is visibly working. Still bounded by BOOT_EXTEND_ABSOLUTE_MS.
  progressFresh = () => false,
  // Called with the 503 body each time our own child answers that it is upgrading (see below).
  onUpgrading = () => {},
  // True while the machine is asleep (the shell's suspend/resume events): the boot budget does not run down meanwhile.
  isSuspended = () => false,
}) {
  let startedAt = now();
  let deadline = startedAt + bootTimeoutMs;
  // Status contract with the server (server/memory/upgrade-health.ts):
  //   200 + identity ........................ ready
  //   503 + {app:"murage", launch:<hash of this launch's nonce>, upgrading:true, ...progress} ... our own child, upgrading: wait, never a foreign owner
  //   connection refused ..................... not up yet, or the pre-listen responder handing the port to the server: poll again
  //   anything else that answers ............. somebody else owns the port (foreign)
  // The proof is the launch nonce: a random value the shell generated for this launch and handed only to the child (through its environment); the
  // child answers with its SHA-256 (`launch`) in its health answers. A process that merely knows the child's (public) pid, or a stale server of ours, cannot answer with it.
  let lastUpgradingAt = null;
  const upgradingRecently = () => lastUpgradingAt !== null && now() - lastUpgradingAt < UPGRADING_FRESH_MS;
  let lastTick = now();
  // A long gap between two turns of this loop is the machine asleep (or the process frozen): the budget does not run down meanwhile.
  const shiftForGap = () => {
    const at = now(), gap = at - lastTick;
    if (gap > SLEEP_GAP_MS || isSuspended()) { const lost = isSuspended() ? Math.max(gap, 0) : gap; startedAt += lost; deadline += lost; }
    lastTick = at;
  };
  // The child upgrading the owner's memory cannot answer health checks until
  // it finishes (a copy of a large messages.db can outlast the normal budget).
  // While it says so, the budget moves forward in small steps up to a hard cap.
  // When the upgrade ends past the normal budget, the child still has the rest
  // of its boot ahead of it: give it one fresh budget from that moment, not
  // whatever is left of the last 5 s step.
  let extended = false;
  let rebudgeted = false;
  const expired = () => {
    if (now() < deadline) return false;
    if (now() >= startedAt + BOOT_EXTEND_LIMIT_MS) {
      if (now() >= startedAt + BOOT_EXTEND_ABSOLUTE_MS) return true;
      if (progressFresh() || upgradingRecently()) { extended = true; deadline = now() + BOOT_EXTEND_STEP_MS; return false; }
      // The upgrade ENDED past the cap (its note is gone): the child still has the rest of its boot ahead of it, so it gets the
      // same one fresh budget as any other finished upgrade. A note that is still there but has stopped moving is a stall: the end.
      if (extended && !rebudgeted && !extendWhile()) { rebudgeted = true; deadline = now() + bootTimeoutMs; return false; }
      return true;
    }
    if (extendWhile() || upgradingRecently()) { extended = true; deadline = now() + BOOT_EXTEND_STEP_MS; return false; }
    if (extended && !rebudgeted) { rebudgeted = true; deadline = now() + bootTimeoutMs; return false; }
    return true;
  };
  for (;;) {
    shiftForGap();
    if (isExited()) return { outcome: "exited" };
    if (expired()) return { outcome: "timeout" };
    const remainingMs = Math.max(1, deadline - now());

    let res;
    // a fresh challenge for every look: the answer must carry an HMAC over it (shared/boot-proof.mjs), so a copied or replayed answer proves nothing
    const challenge = newChallenge();
    try {
      res = await fetchImpl(`http://127.0.0.1:${port}/api/health`, {
        signal: AbortSignal.timeout(remainingMs),
        headers: { [PROOF_CHALLENGE_HEADER]: challenge },
      });
    } catch {
      // Not up yet, or this probe ran into the wall-clock budget — either way
      // back off to the poll interval, then let the loop condition decide.
      const intervalMs =
        now() - startedAt < BOOT_PROBE_FAST_WINDOW_MS ? BOOT_PROBE_FAST_INTERVAL_MS : BOOT_PROBE_INTERVAL_MS;
      await sleep(Math.min(intervalMs, Math.max(1, deadline - now())));
      continue;
    }
    const body = await res.json().catch(() => null);
    // A sleep during the request is a gap like any other: the clock is looked at again, and the budget moved by the time asleep, before any deadline is judged.
    shiftForGap();
    // Body consumption is covered by the same abort signal as fetch. If it
    // reaches the deadline, a null body means the probe timed out—not that a
    // different process answered on the port.
    if (expired()) return { outcome: "timeout" };
    // The nonce is read NOW, after the response landed (a getter, so a caller that has none yet identifies nothing).
    const expected = nonce();
    // `launch` is only a label; ownership is the HMAC over this probe's challenge and the answer's status fields
    const ours = typeof expected === "string" && expected.length > 0 && body?.app === "murage" && body.launch === launchOf(expected) && proofHolds(expected, challenge, body, res.status);
    if (res.status === 503 && ours && body.upgrading === true) {
      lastUpgradingAt = now();
      try { onUpgrading(body); } catch { /* a screen glitch never blocks startup */ }
      await sleep(Math.min(BOOT_UPGRADING_POLL_MS, Math.max(1, deadline - now())));
      continue;
    }
    const identified =
      res.ok &&
      ours &&
      body.static === true;
    if (!identified) return { outcome: "foreign-owner" };
    // A response that finishes after the budget must not count as a healthy
    // boot: re-check the clock (after the time asleep is taken out) before declaring victory.
    shiftForGap();
    if (expired()) return { outcome: "timeout" };
    return { outcome: "ready", latencyMs: now() - startedAt };
  }
}
