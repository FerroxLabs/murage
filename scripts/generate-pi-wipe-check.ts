import {build} from 'esbuild';
import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

export async function generatePiWipeCheck(root = fileURLToPath(new URL('../', import.meta.url))): Promise<string> {
 const result = await build({
  absWorkingDir: root,
  stdin: {
   contents: "export * from './server/wipe-breaker.ts';\nexport {RootRegistry} from './server/wipe/registry.ts';\nexport {noLimitsWipe} from './server/no-limits-wipe.ts';\n",
   resolveDir: root,
   sourcefile: 'pi-wipe-check-entry.ts',
   loader: 'ts',
  },
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  // The checker serializes pure mount readers into its probe workers.
  // Keep their lexical names and bodies, without injected naming helpers.
  minify: false,
  write: false,
  banner: {js: '// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by scripts/generate-pi-wipe-check.ts; do not edit.\n// secret-scan: fixture\n// Owner Pi consumer/staging: pi-wipe-seam-b; owner checker: wipe-fable / wg-final.'},
 });
 return result.outputFiles[0]!.text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
 writeFileSync(new URL('../server/drivers/pi-wipe-check.generated.mjs', import.meta.url), await generatePiWipeCheck());
}
