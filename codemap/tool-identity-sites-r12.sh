#!/bin/sh
# r1.2 section 8 site inventory, produced by rg so completeness is checkable. Each pattern is one class of approval
# identity site; sites.out lists every hit as  P<n> <file>:<line>: <text>. Re-run after any merge; S6 diffs it.
set -eu
WT=${WT:-/work/build/nolimint/wt}
OUT=${1:-$(cd "$(dirname "$0")" && pwd)/sites.out}
cd "$WT"
: > "$OUT"
echo "# base $(git rev-parse --short=9 HEAD)  generated by sites.sh" >> "$OUT"
n=0
while IFS='|' read -r tag pat; do
  [ -z "$tag" ] && continue
  n=$((n+1))
  hits=$(rg -n --no-heading -t ts -g '!*.test.ts' -g '!**/testing/**' -e "$pat" server shared 2>/dev/null || true)
  c=$(printf '%s' "$hits" | grep -c . || true)
  echo "## $tag  /$pat/  hits=$c" >> "$OUT"
  printf '%s\n' "$hits" | grep . | awk -v t="${tag%% *}" '{print t " " $0}' | cut -c1-220 >> "$OUT" || true
done <<'PATTERNS'
P1 resolveToolIdentity|resolveToolIdentity
P2 request.opened emitters (all drivers)|type: "request\.opened"
P3 permission request emitters|requestType: "permission"
P4 identity object built inline|toolIdentity\s*:
P5 standing allow record/accept|toolAllows\.(record|accepts)
P6 resolveCall callers|resolveCall\(
P7 No-limits finalizer|finalizeNoLimits\(|noLimitsWipe\(
P8 tripwire|toolTripwire|tool-tripwire
P9 outside-call registration|acpOutsideCall\(
P10 model-written name/input reads|[.\[]["']?(tool_name|toolName|tool_input|toolInput)\b
P11 commandArgument readers|commandArgument\(
P12 Hermes hook normaliser|normalizeHermesAsk
P13 own-call digest (r3.1)|ownCallDigest
P14 Hermes hook overlay|pre_tool_call|HERMES_OWNER_HOOK_EVENTS
P15 Hermes mode|session/set_mode|currentModeId
P16 Claude/Codex native identity producers|tool_use\.name|args\.tool_name|item\.type === "(commandExecution|fileChange|mcpToolCall)"
PATTERNS
echo "# patterns=$n" >> "$OUT"
grep '^## ' "$OUT"
