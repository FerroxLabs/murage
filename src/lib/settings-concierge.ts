// SETTINGS-UX-1011 S9: the "every setting" Help page, made from the Settings index each release. One section per
// entry (its name, where it is, the line that says when it is off, its address), so the help index quotes one setting
// at a time and the concierge can answer "where do I set Nova's working folder" with a link that opens it, on every
// engine. Written to the docs by scripts/help/settings-concierge-page.mjs; settings-concierge.test.ts fails when the
// committed page is stale. Never loaded by the app.
import { BOT_SETTINGS_SECTIONS } from "@/components/bot-settings-sections";
import { settingsAddressFor } from "./settings-address";
import { SETTINGS_INDEX, type SettingsIndexEntry } from "./settings-index";
import { settingsPageLabel } from "./settings-sections";

export const CONCIERGE_PAGE_FILE = "apps/docs/content/docs/features/every-setting.mdx";

/** MDX reads braces and angle brackets as code; a label never needs them. */
const plain = (text: string) => text.replace(/[{}<>]/g, "").replace(/\s+/g, " ").trim();

function where(entry: SettingsIndexEntry): string[] {
  if (entry.scope === "app") return ["Settings", settingsPageLabel(entry.section), ...(entry.advanced ? ["Advanced"] : [])];
  const section = BOT_SETTINGS_SECTIONS.find((item) => item.id === entry.section)!;
  return ["Bot settings", section.label];
}

export function settingsConciergeMdx(index: readonly SettingsIndexEntry[] = SETTINGS_INDEX): string {
  const lines = [
    "---",
    "title: Every setting",
    "description: Every setting in Murage, where it is, and the link that opens it.",
    "icon: Settings",
    "---",
    "",
    "{/* GENERATED by scripts/help/settings-concierge-page.mjs from the Settings index. Do not edit by hand. */}",
    "",
    "Every setting in the app and in each bot's settings, with the path to it and its address. Open an address from a chat",
    "and Murage goes straight to that setting and highlights it. A bot address opens in the bot you are looking at.",
    "",
  ];
  for (const entry of index) {
    const path = where(entry).map(plain);
    const label = plain(entry.label());
    lines.push(`## ${path.slice(1).join(", ")}: ${label}`, "", `**${[...path, label].join(" → ")}**`, "");
    if (entry.surface === "desktop") lines.push("On the computer running Murage.", "");
    if (entry.gate) lines.push(`When it is off: ${plain(entry.gate.reason())}`, "");
    lines.push(`Address: ${settingsAddressFor(entry)}`, "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}
