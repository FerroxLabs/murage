import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export type Disposition = { s: "inproc"; site: string } | { s: "forced"; cut: string } | { s: "pin"; pin: string } | { s: "open" };
export type DesignRow = { id: string; section: string; source: string; line: number };

export const DESIGN_PATH = fileURLToPath(new URL("../../../designs/memv2-I/KILLSUITE.md", import.meta.url));

/** Every row of every table in the design: `| ID | Source | ...` (the header row "ID" excluded). Throws on a duplicate ID. */
export function designRows(text = readFileSync(DESIGN_PATH, "utf8")): DesignRow[] {
  const rows: DesignRow[] = [], seen = new Set<string>();
  let section = "";
  text.split("\n").forEach((line, index) => {
    if (line.startsWith("#")) { section = line.replace(/^#+\s*/, ""); return; }
    const match = /^\| ([A-Za-z0-9][A-Za-z0-9-]*) \|([^|]*)\|/.exec(line);
    if (!match || match[1] === "ID") return;
    if (seen.has(match[1]!)) throw new Error(`KILLSUITE.md: duplicate row ID ${match[1]} at line ${index + 1}`);
    seen.add(match[1]!);
    rows.push({ id: match[1]!, section, source: match[2]!.trim(), line: index + 1 });
  });
  return rows;
}

/** A design source cell `file.ts:NNN` as a repo path (paths are under server/memory/ unless they start with server/), or null. */
export function sourceAnchor(cell: string): { file: string; line: number; pin?: string } | null {
  const match = /^`([\w./-]+\.(?:ts|mjs|js)):(\d+)/.exec(cell);
  if (!match) return null;
  const pin = /@ `([0-9a-f]{7,40})`/.exec(cell)?.[1];
  return { file: match[1]!.startsWith("server/") ? match[1]! : `server/memory/${match[1]}`, line: Number(match[2]), ...(pin ? { pin } : {}) };
}

