/** The design rows the kill harness drives, grouped by its kill site key (task:kind). */
export function harnessSites(reviewed: Record<string, Disposition> = REVIEWED): Map<string, string[]> {
  const sites = new Map<string, string[]>();
  for (const [id, disposition] of Object.entries(reviewed)) {
    if (disposition.s !== "inproc") continue;
    sites.set(disposition.site, [...(sites.get(disposition.site) ?? []), id]);
  }
  return sites;
}

/** The design rows driven by a forced child-kill case (migration-v2-kill-forced.test.ts), grouped by cut (task:kind). */
export function forcedCuts(reviewed: Record<string, Disposition> = REVIEWED): Map<string, string[]> {
  const cuts = new Map<string, string[]>();
  for (const [id, disposition] of Object.entries(reviewed)) if (disposition.s === "forced") cuts.set(disposition.cut, [...(cuts.get(disposition.cut) ?? []), id]);
  return cuts;
}

