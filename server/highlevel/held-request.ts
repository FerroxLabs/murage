const hash = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex');

const shape = (): never => { throw new ActionRefused('request_shape', 'This request does not match the operation, resource or location.'); };

function digest(f: Omit<FrozenRequest, 'requestDigest'>): string {
  return hash(canonicalJson(['highlevel-request', 2, f.operation, f.method, f.path, f.resource, f.query, f.bodyKind, f.contentType, f.bodySha256, f.upload,
    ...(f.completionKind ? [f.completionKind] : [])]));
}

function checkLocation(value: unknown, locationId: string): void {
  if (!value || typeof value !== 'object') return;
  for (const [key, v] of Object.entries(value)) { if ((key === 'locationId' || key === 'altId') && v !== locationId) shape(); checkLocation(v, locationId); }
}

export interface FrozenUploadRef { readonly field: string; readonly name: string; readonly size: number; readonly sha256: string; readonly contentType: string }

export interface FrozenRequest {
  /** An incomplete non-secret template; generic dispatch must refuse it. */
  // Version 1 binds 32 private generated bytes and recipient password setup in HighLevel.
  // Changing either policy requires a new version and a fresh exact review.
  readonly completionKind?: 'private_generated_password_v1';
  readonly operation: OperationId; readonly method: HighLevelMethod; readonly path: string; readonly resource: string;
  readonly query: readonly (readonly [string, string])[];
  readonly bodyKind: "none" | "json" | "multipart";
  readonly contentType: string | null;
  /** SHA-256 of reviewed bytes: the non-secret template for private generation,
   * otherwise exact wire bytes including the frozen multipart boundary. */
  readonly bodySha256: string;
  readonly upload: FrozenUploadRef | null;
  /** The reviewed-byte digest, with the completion requirement when present. */
  readonly requestDigest: string;
}

export interface FrozenSendCopy {
  url: URL; method: HighLevelMethod; headers: Record<string, string>; body?: Uint8Array;
  fileOffset: number | null; fileLength: number | null;
}

export class HeldRequest {
  #validateCopy(out: FrozenSendCopy, approvedRequestDigest?: string): void {
    const f = this.frozen, body = out.body ?? new Uint8Array();
    const stale = (): never => { throw new ActionRefused('stale', 'The reviewed request changed. Nothing was sent.'); };
    if (!(out.url instanceof URL) || out.url.origin !== HIGHLEVEL_API_ORIGIN || out.url.username || out.url.password || out.url.hash
      || !(endpointFor(f.operation, out.method, out.url.pathname) || (frozenOperationExtension(f)?.endpoint.method === out.method && frozenOperationExtension(f)?.endpoint.path.test(out.url.pathname))) || out.method !== f.method || out.url.pathname !== f.path
      || (out.headers['content-type'] ?? null) !== f.contentType || Object.keys(out.headers).some(k => k !== 'content-type')
      || hash(body) !== f.bodySha256 || (f.bodyKind === 'none' && out.body !== undefined)) return stale();
    const query = [...out.url.searchParams.entries()].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
    const computed = digest({ ...f, method: out.method, path: out.url.pathname, query, contentType: out.headers['content-type'] ?? null, bodySha256: hash(body) });
    if (computed !== f.requestDigest || (approvedRequestDigest !== undefined && computed !== approvedRequestDigest)) return stale();
    if (out.fileOffset !== (f.upload ? this.#fileOffset : null) || out.fileLength !== (f.upload ? this.#fileLength : null)) return stale();
    if (f.upload && (this.#fileLength !== f.upload.size || this.#fileOffset + this.#fileLength > body.length || hash(body.subarray(this.#fileOffset, this.#fileOffset + this.#fileLength)) !== f.upload.sha256)) return stale();
  }

  readonly #approvalContext: RequestApprovalContext | undefined;
  get approvalContextDigest(): string | undefined { return this.#approvalContext ? hash(canonicalJson(this.#approvalContext)) : undefined; }
  approvalContextCopy(): RequestApprovalContext | undefined { return structuredClone(this.#approvalContext); }
  readonly #body: Uint8Array;
  readonly #fileOffset: number;
  readonly #fileLength: number;
  private constructor(frozen: FrozenRequest, bytes: Uint8Array, offset: number, length: number, approvalContext?: RequestApprovalContext) {
    this.#approvalContext = approvalContext ? JSON.parse(Buffer.from(canonicalJson(approvalContext)).toString()) : undefined;
    this.frozen = Object.freeze(frozen); this.#body = Buffer.from(bytes); this.#fileOffset = offset; this.#fileLength = length;
    heldValidators.set(this, (out, approved) => this.#validateCopy(out, approved));
    Object.defineProperty(this, 'frozen', { writable: false, configurable: false });
  }
  static freeze(spec: OperationSpec<any>, draft: RequestDraft, ctx: OperationRunContext): HeldRequest {
    const row = spec.row, endpoint = endpointFor(spec.id, spec.endpoint.method, draft.path) ?? operationExtension(row)?.endpoint;
    if (!row || row.disposition !== 'ready' || row.id !== spec.id || row.family !== spec.family || row.method !== spec.endpoint.method
      || row.version !== spec.endpoint.version || row.scope !== spec.endpoint.scope || !endpoint
      || !endpoint.path.test(draft.path) || endpoint.method !== row.method || endpoint.version !== row.version || endpoint.scope !== row.scope || endpoint.retry !== (spec.risk === 'R' ? 'read' : 'write')
      || spec.endpoint.path.source !== highlevelEndpointPattern(row.path).source || spec.args !== row.argsSchema) return shape();
    const parts = draft.path.split('/'), template = row.path.split('/');
    for (let i = 0; i < template.length; i++) if (/^(?::locationId|\{locationId\})$/.test(template[i]!) && decodeURIComponent(parts[i] ?? '') !== ctx.locationId) return shape();
    if (row.pathResourceSegment === null) { if (draft.resource !== `location:${ctx.locationId}`) return shape(); }
    else {
      const resource = draft.resource.split(':');
      if (resource.length !== 3 || resource[0] !== spec.family || !resource[1] || !resource[2] || decodeURIComponent(parts[row.pathResourceSegment] ?? '') !== resource[2]) return shape();
    }
    if (draft.query && (typeof draft.query !== 'object' || Array.isArray(draft.query) || Object.values(draft.query).some(v => typeof v !== 'string'))) return shape();
    const query = Object.entries(draft.query ?? {}).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(pair => Object.freeze(pair));
    checkLocation(draft.query, ctx.locationId);
    let bytes: Uint8Array = new Uint8Array(), contentType: string | null = null, upload: FrozenUploadRef | null = null, offset = 0, length = 0;
    const bodyKind = draft.body?.kind ?? 'none';
    if (spec.endpoint.method === 'GET' && draft.body !== undefined) return shape();
    if (draft.body === undefined && spec.endpoint.method !== 'GET' && row.bodySchema && !row.bodySchema.safeParse(undefined).success) return shape();
    if (draft.body?.kind === 'json') {
      // Validate without transforming: the exact prepared value is what is frozen.
      const parsed = (spec.id === 'users.create' ? userCreateReviewSchema : row.bodySchema)?.safeParse(draft.body.value);
      if (!parsed?.success) return shape();
      if (spec.id === 'users.create') {
        const template = parsed.data as Record<string, unknown>;
        if (!ctx.companyId || template.companyId !== ctx.companyId || !Array.isArray(template.locationIds)
          || template.locationIds.length !== 1 || template.locationIds[0] !== ctx.locationId) return shape();
      }
      bytes = canonicalJson(draft.body.value);
      if (!Buffer.from(bytes).equals(Buffer.from(canonicalJson(parsed.data)))) return shape(); checkLocation(JSON.parse(Buffer.from(bytes).toString()), ctx.locationId); contentType = 'application/json';
    } else if (draft.body?.kind === 'multipart') {
      if (spec.id !== 'media.files.upload' && spec.id !== 'conversations.attachment.upload') return shape();
      const parsed = row.bodySchema?.safeParse(draft.body.fields);
      if (!parsed?.success || !Buffer.from(canonicalJson(draft.body.fields)).equals(Buffer.from(canonicalJson(parsed.data)))) return shape();
      checkLocation(draft.body.fields, ctx.locationId);
      const multipart = assembleMultipart(draft.body.fields, draft.body.file);
      bytes = multipart.bytes; contentType = multipart.contentType; offset = multipart.fileOffset; length = multipart.fileLength;
      const file = draft.body.file;
      upload = Object.freeze({ field: file.field, name: file.upload.name, size: file.upload.size, sha256: file.upload.sha256, contentType: file.upload.contentType });
    } else if (draft.body !== undefined) return shape();
    const frozen: Omit<FrozenRequest, 'requestDigest'> = { operation: spec.id, method: spec.endpoint.method, path: draft.path, resource: draft.resource, query: Object.freeze(query), bodyKind, contentType, bodySha256: hash(bytes), upload,
      ...(spec.id === 'users.create' ? { completionKind: 'private_generated_password_v1' as const } : {}) };
    const held = new HeldRequest({ ...frozen, requestDigest: digest(frozen) }, bytes, offset, length, draft.approvalContext);
    bindOperationExtension(held.frozen, row, draft);
    heldOperationHooks.set(held.frozen, spec);
    (spec as OperationSpec<any> & OperationHooks).retainRequest?.(held, ctx);
    return held;
  }
  readonly frozen: FrozenRequest;
  sendCopy(): FrozenSendCopy {
    const f = this.frozen, url = new URL(f.path, HIGHLEVEL_API_ORIGIN);
    for (const [k, v] of f.query) url.searchParams.append(k, v);
    return { url, fileOffset: f.upload ? this.#fileOffset : null, fileLength: f.upload ? this.#fileLength : null, method: f.method, headers: f.contentType ? { 'content-type': f.contentType } : {}, ...(f.bodyKind === 'none' ? {} : { body: Buffer.from(this.#body) }) };
  }
}

export function sendFrozen(client: HighLevelClient, ctx: HighLevelCallContext, held: HeldRequest, approvedRequestDigest: string): Promise<unknown> {
  return held.frozen.operation === 'users.create' ? client.sendHeldWithPrivatePassword(ctx, held, approvedRequestDigest) : client.sendHeld(ctx, held, approvedRequestDigest);
}

export function sendFrozenRead(client: HighLevelClient, ctx: HighLevelCallContext, held: HeldRequest): Promise<unknown> { return client.sendHeld(ctx, held); }
