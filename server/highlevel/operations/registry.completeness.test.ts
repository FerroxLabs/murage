it("T-F1 registry.zeroQualifyAtF0 and literal 181 ids", () => {
  const rows = (registry as any).HIGHLEVEL_OPERATION_MANIFEST;
  expect(rows).toBeDefined();
  expect(rows.map((r: any) => r.id).sort()).toEqual([...IDS].sort());
  expect(new Set(rows.map((r: any) => r.id)).size).toBe(181);
  expect(rows.every((r: any) => ["ready", "provider_absent"].includes(r.disposition))).toBe(true);
});
it("T-F2 registry.completenessScopedToIntegrated", () => {
  const check = (registry as any).assertRegistryCompleteness;
  expect(check).toBeTypeOf("function");
  expect(() => check([], [])).not.toThrow();
  expect(() => check([], ["contacts"])).toThrow(/contacts/);
  const present = HIGHLEVEL_FAMILIES.flatMap(f => registry.familyOperations(f));
  expect(() => check(present)).not.toThrow();
});
