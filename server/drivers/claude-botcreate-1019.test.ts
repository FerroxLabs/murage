import { chmodSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, expect, it } from 'vitest';
import { ClaudeDriver } from './claude.ts';
import type { ProviderInstance } from '../contracts.ts';
import { recordEvents } from '../testing/events.ts';
import { removeTempDirSync } from '../testing/cleanup.ts';
import { beginOutsideTurn, forgetOutsideState, observeOutsideMarks, turnOutsideRead, wireOutsideStore } from '../email/external-marks.ts';
import { fileOutsideStore } from '../outside-store.ts';
import { Ledger, settle_verdict } from '../turn-settle.ts';
const cli = fileURLToPath(new URL('../testing/fake-claude-cli.ts', import.meta.url));
let instance: ProviderInstance | undefined; let home = ''; let off: (() => void) | undefined;
afterEach(async () => { off?.(); await instance?.dispose(); instance = undefined; forgetOutsideState(); if (home) removeTempDirSync(home); });
it('r331 actual Claude closes a complete helper row cleanly without clearing its mark', async () => {
  chmodSync(cli, 0o755); home = mkdtempSync(join(tmpdir(), 'murage-botcreate-claude-'));
  expect(wireOutsideStore(fileOutsideStore(join(home, 'outside.jsonl')))).toBe(true);
  beginOutsideTurn('T', 'fixture', undefined, false);
  const ledger = new Ledger(); ledger.open('G', 'T', 'claude', 'own');
  off = observeOutsideMarks((thread, source, lifecycle) => ledger.mark(thread, source, lifecycle));
  instance = await ClaudeDriver.create({ instanceId: 'fixture', displayName: 'Fixture', enabled: true, config: { cli, permissionMode: 'acceptEdits' }, environment: { HOME: home, USERPROFILE: home, FAKE_CLAUDE_BG_ASKS: '0' } });
  const recorder = recordEvents(instance.adapter);
  const { turnId } = await instance.adapter.sendTurn({ threadId: 'T', text: 'go __fixture_background__', cwd: home });
  const done = await recorder.until(e => e.type === 'turn.completed' && e.turnId === turnId, 15_000);
  if (done.type !== 'turn.completed') throw new Error('missing terminal');
  expect(done).toMatchObject({ ok: true, readsComplete: true, helperRow: { name: 'claude-bg', readsComplete: true, outsideRead: false, interrupted: false } });
  expect(turnOutsideRead('T')).toBe('helper');
  expect(settle_verdict(ledger.take('G')!, done, turnOutsideRead('T'), 'own')).toBe('clean');
  expect(turnOutsideRead('T')).toBe('helper'); recorder.stop();
}, 20_000);
