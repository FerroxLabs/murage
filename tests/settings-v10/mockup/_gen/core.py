def win(space, cur, title, sub='', body='', aside='', crumbs=None, back=None, sh='', frame='', view='simple',
        query='', learn=None, railscreen=False, pm='', needs=NEEDS, empty=False, headless=False, banner='', last=None):
    """One app window. crumbs = destinations only; the last is this place. back = (label, href) when Settings has history."""
    root = (BOTCTX['n'], 'bot-reach.html') if space == 'bot' else ('Settings', 'overview.html')
    cr = [root] + (crumbs or []) + [(last or title, None)]
    if space == 'bot': cr = [('Settings', 'overview.html')] + cr
    ch = ''
    for i, (t, f) in enumerate(cr):
        if i: ch += ic('chev')
        ch += f'<b aria-current="page">{e(t)}</b>' if f is None else f'<a href="{f}">{e(t)}</a>'
    bk = f'<a class="backto" href="{back[1]}">{ic("back")} {e(back[0])}</a>' if back else ''
    lm = f' <a class="lnk" href="help.html#help.{e(learn[1])}" data-help="{e(learn[1])}">{e(learn[0])}</a>' if learn else ''
    head = '' if headless else f'<header class="head"><h2>{e(title)}</h2><p>{sub}{lm}</p>{pm}</header>'
    covered = bool(sh) and frame in ('f-narrow', 'f-phone')   # under 1024 px a sheet covers the page: it is modal and everything behind it is inert, the Back and breadcrumb bar included (Astra r5 14, Visual QA H02)
    mid = 'page-' + _lid()
    if covered:   # v7: the covering sheet owns one header with the single Back, the title and Close; the bar behind it is not drawn at all (Visual QA r6 H01, M05)
        bb = f'<button type="button" class="backto insheet" aria-label="Back to {e(back[0])}">{ic("back")} {e(back[0])}</button>' if back else ''
        sh = sh.replace('<h4 ', f'<div class="shead">{bb}<h4 ', 1).replace('</h4>', '</h4></div>', 1)
        sh = sh.replace('aria-modal="false"', 'aria-modal="true"')
    right = sh if sh else (f'<aside class="aside" aria-label="Help for this page">{aside}</aside>' if aside else '')
    fr = (' ' + frame if frame else '') + (' railscreen' if railscreen else '')
    tb = '' if frame == 'f-phone' else '<div class="titlebar"><span class="lights"><i></i><i></i><i></i></span><span class="t">Murage</span></div>'
    return (f'<div class="win{fr}">{tb}<div class="app{" railscreen" if railscreen else ""}"><aside class="side" aria-label="Settings"{" inert" if covered else ""}>{rail(space, cur, view, query, needs, empty, esc=not sh, skip=mid)}</aside>'
            f'<main class="main"><div class="top"{" inert hidden" if covered else ""}>{bk}<nav class="crumbs" aria-label="You are here">{ch}</nav></div>'
            f'<div class="body{" has-sheet" if sh else ""}"><div class="col" id="{mid}" tabindex="-1"{" inert" if covered else ""}>{head}{banner}{body}</div>{right}</div></main></div></div>')

