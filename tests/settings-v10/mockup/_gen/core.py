def A(text, id, kind='', note='', status='today', href=None, disabled=False, slabel=None):
    """An action button: something that happens now. Registered in the actions inventory (Appendix E)."""
    _reg(id, slabel or text, 'action', note, status)   # slabel = the unique label search shows when the visible text repeats (Apply, Check again)
