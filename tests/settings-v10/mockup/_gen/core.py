def R(title, desc='', icon=None, id=None, ref=None, st=None, on=None, val=None, open=None, go=None, act='',
      tg=None, av=None, cls='', mk=None, end='', dis=False, rawdesc=None):
    """One row. id = this is the control's one home. ref = a signpost to a home elsewhere.
    open = opens this row's sheet (href or True). go = (page label, href): leaves for another page."""
    lid = _lid()
    _reg(id, title)
    if ref: REG['refs'].append((REG['cur'], ref, title))
    a = ''
    if id: a += f' id="{id}" data-id="{id}"'
    if ref: a += f' data-ref="{ref}"'
    if av: m = f'<span class="mk plain"><span class="av s {av[1]}">{e(av[0])}</span></span>'
    elif mk: m = f'<span class="mk{" ours" if mk[1:] else ""}">{e(mk[0])}</span>'
    elif icon: m = f'<span class="mk">{ic(icon)}</span>'
    else: m = ''
    tags = ''.join(tag(*((t,) if isinstance(t, str) else t)) for t in (tg or []))
    d = rawdesc if rawdesc is not None else e(desc)
    tx = f'<span class="tx"><b id="{lid}">{e(title)}{tags}</b>' + (f'<span>{d}</span>' if d else '') + '</span>'
    parts, n = [], 0
    if st:
        parts.append(txt(st[1]) if st[0] == 't' else pill(st[0], st[1])); n += 1
    if end: parts.append(end)
    if val is not None: parts.append(pick(val, title)); n += 1
    if on is not None: parts.append(sw(on, lid, dis)); n += 1
    if act: parts.append(act); n += 1
    en = f'<span class="end{" two" if n > 1 else ""}">' + ''.join(parts) + '</span>' if parts else ''
    ro = ''
    if go:
        ro = f'<a class="ro go" href="{go[1]}" aria-label="{e(title)}: go to {e(go[0])}"><span class="golab">{e(go[0])}</span>{ic("go")}</a>'
    elif open:
        if isinstance(open, str):
            ro = f'<a class="ro" role="button" aria-haspopup="dialog" href="{open}" aria-label="Open {e(title)}">{ic("chev")}</a>'
        else:
            ro = f'<button type="button" class="ro" aria-haspopup="dialog" aria-label="Open {e(title)}">{ic("chev")}</button>'
    return f'<div class="r{" "+cls if cls else ""}"{a}>{m}{tx}{en}{ro}</div>'

