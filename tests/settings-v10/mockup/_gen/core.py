def e(s): return html.escape(str(s), quote=True)
def ic(n, cls=''): return f'<span class="i i-{n}{" "+cls if cls else ""}" aria-hidden="true"></span>'

REG = {'ids': {}, 'refs': [], 'actions': [], 'cur': '', 'view': 'simple', 'canon': True, 'n': 0}

def _reg(i, label, kind='setting', note='', status=''):
    if not i or not REG['canon']: return
    REG['ids'].setdefault(i, []).append((REG['cur'], label, kind))
    if kind == 'action':
        REG['actions'].append({'id': i, 'label': label, 'page': REG['cur'], 'note': note, 'status': status})

def _lid():
    REG['n'] += 1
    return f't{REG["n"]}'

def pill(kind, text): return f'<span class="pill{" "+kind if kind else ""}">{e(text)}</span>'
