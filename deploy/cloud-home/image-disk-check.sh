die() { echo "image-disk-check: REFUSED $*" >&2; exit 1; }

field() { # field KEY LINE: the value of KEY="..." in an lsblk -P line
    local re="(^| )$1=\"([^\"]*)\""
    [[ $2 =~ $re ]] || return 1
    printf '%s' "${BASH_REMATCH[2]}"
}

