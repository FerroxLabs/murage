closure_pins() {
    if [[ -n ${MURAGE_DISKCHECK_CLOSURE_FILE:-} ]]; then cat -- "$MURAGE_DISKCHECK_CLOSURE_FILE"; return; fi
    case $ENVN in staging) "closure_staging_$ARCH" ;; *) : ;; esac
